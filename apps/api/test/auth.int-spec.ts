import { categories, userSettings } from '@savesphere/db';
import { eq } from 'drizzle-orm';
import request from 'supertest';
import { createTestApp, signUp, type TestApp } from './helpers/app.js';

describe('auth & provisioning', () => {
	let t: TestApp;
	beforeAll(async () => {
		t = await createTestApp();
	});
	afterAll(() => t.close());

	it('rejects unauthenticated requests with the error envelope', async () => {
		const response = await request(t.app.getHttpServer()).get('/api/me').expect(401);
		expect(response.body).toEqual({
			success: false,
			error: { code: 'UNAUTHORIZED', message: 'Authentication required' }
		});
	});

	it('keeps the health check public', async () => {
		const response = await request(t.app.getHttpServer()).get('/api/health').expect(200);
		expect(response.body).toEqual({ success: true, data: { status: 'ok' } });
	});

	it('signs up, provisions defaults and resolves the session', async () => {
		const { agent, userId, email } = await signUp(t.app);
		expect(userId).toMatch(/^[0-9a-f]{8}-[0-9a-f]{4}-7/); // UUIDv7 generated by Postgres

		const me = await agent.get('/api/me').expect(200);
		expect(me.body.data).toEqual({ id: userId, email, name: 'Test User' });

		const [settings] = await t.db.db
			.select()
			.from(userSettings)
			.where(eq(userSettings.userId, userId));
		expect(settings?.baseCurrency).toBe('USD');
		const userCategories = await t.db.db
			.select()
			.from(categories)
			.where(eq(categories.userId, userId));
		expect(userCategories.length).toBeGreaterThan(10);
	});

	it('updates settings and validates them', async () => {
		const { agent } = await signUp(t.app);
		const updated = await agent
			.patch('/api/me/settings')
			.send({ baseCurrency: 'COP', timezone: 'America/Bogota' })
			.expect(200);
		expect(updated.body.data).toMatchObject({ baseCurrency: 'COP', timezone: 'America/Bogota' });

		await agent.patch('/api/me/settings').send({ timezone: 'Mars/Olympus' }).expect(422);
		await agent.patch('/api/me/settings').send({ baseCurrency: 'XYZ' }).expect(422);
	});
});
